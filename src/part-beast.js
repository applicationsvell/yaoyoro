/* ---- なめらかな線と、太さの変わる胴 ---- */
function crPts(pts, n) {
  const out = [];
  for (let i = 0; i < pts.length - 1; i++) {
    const p0 = pts[Math.max(0, i - 1)], p1 = pts[i], p2 = pts[i + 1], p3 = pts[Math.min(pts.length - 1, i + 2)];
    for (let k = 0; k < n; k++) {
      const t = k / n, t2 = t * t, t3 = t2 * t;
      const f = j => 0.5 * (2 * p1[j] + (-p0[j] + p2[j]) * t + (2 * p0[j] - 5 * p1[j] + 4 * p2[j] - p3[j]) * t2 + (-p0[j] + 3 * p1[j] - 3 * p2[j] + p3[j]) * t3);
      out.push([f(0), f(1)]);
    }
  }
  out.push(pts[pts.length - 1].slice());
  return out;
}
const ptsD = (a, close) => a.map((p, i) => (i ? 'L' : 'M') + f1(p[0]) + ' ' + f1(p[1])).join('') + (close ? 'Z' : '');
function spline(pts, n) { return ptsD(crPts(pts, n || 8)); }
/* 中心線 pts に沿って、太さ wf(t) の胴を作る。back は背中側（+）の点、belly は腹側の点 */
function tubeGeo(pts, wf, n) {
  const c = crPts(pts, n || 8), m = c.length;
  const L = [], Rr = [], N = [], W = [];
  for (let i = 0; i < m; i++) {
    const a = c[Math.max(0, i - 1)], b = c[Math.min(m - 1, i + 1)];
    let dx = b[0] - a[0], dy = b[1] - a[1]; const len = Math.hypot(dx, dy) || 1; dx /= len; dy /= len;
    const nx = -dy, ny = dx, w = wf(i / (m - 1)) / 2;
    N.push([nx, ny]); W.push(w);
    L.push([c[i][0] + nx * w, c[i][1] + ny * w]); Rr.push([c[i][0] - nx * w, c[i][1] - ny * w]);
  }
  return { c, L, R: Rr, N, W, m };
}
function tubePath(g) { return ptsD(g.L.concat(g.R.slice().reverse()), true); }
/* 龍や蛇の胴：鱗・腹板・背びれ */
function serpent(pts, wf, o) {
  o = o || {};
  const g = tubeGeo(pts, wf, 10);
  let s = '';
  /* 背びれ（背中側） */
  if (o.fin) for (let i = 4; i < g.m - 6; i += 4) {
    const p = g.L[i], q = g.L[i + 3], nn = g.N[i + 1], h = g.W[i] * 0.9 + 1.2;
    s += P('M' + f1(p[0]) + ' ' + f1(p[1]) + 'L' + f1((p[0] + q[0]) / 2 + nn[0] * h + (q[0] - p[0]) * .6) + ' ' + f1((p[1] + q[1]) / 2 + nn[1] * h + (q[1] - p[1]) * .6) + 'L' + f1(q[0]) + ' ' + f1(q[1]) + 'Z', o.fin, ' stroke-width=".8"');
  }
  s += P(tubePath(g), o.fill || gid('teal'));
  /* 腹（腹側に細い帯）と腹板 */
  if (o.belly) {
    const bl = [], br = [];
    for (let i = 0; i < g.m; i++) { const w = g.W[i], c = g.c[i], nn = g.N[i]; bl.push([c[0] - nn[0] * w * .25, c[1] - nn[1] * w * .25]); br.push([c[0] - nn[0] * w * .95, c[1] - nn[1] * w * .95]); }
    s += Pn(ptsD(bl.concat(br.reverse()), true), o.belly);
    for (let i = 3; i < g.m - 3; i += 2) { const c = g.c[i], nn = g.N[i], w = g.W[i]; s += L('M' + f1(c[0] - nn[0] * w * .3) + ' ' + f1(c[1] - nn[1] * w * .3) + 'L' + f1(c[0] - nn[0] * w * .92) + ' ' + f1(c[1] - nn[1] * w * .92), INK, .5, op(.45)); }
  }
  /* 鱗（背中側に小さな弧） */
  if (o.scale) for (let i = 3; i < g.m - 4; i += 2) {
    const c = g.c[i], nn = g.N[i], w = g.W[i]; if (w < 1.6) continue;
    for (const k of [.15, .55]) {
      const x = c[0] + nn[0] * w * k, y = c[1] + nn[1] * w * k, r = Math.max(.9, w * .28);
      const tx = -nn[1], ty = nn[0];
      s += L('M' + f1(x - tx * r) + ' ' + f1(y - ty * r) + 'Q' + f1(x + nn[0] * r * 1.1) + ' ' + f1(y + nn[1] * r * 1.1) + ' ' + f1(x + tx * r) + ' ' + f1(y + ty * r), o.scale, .55, op(.8));
    }
  }
  /* 光 */
  const hl = []; for (let i = 2; i < g.m - 4; i++) { const c = g.c[i], nn = g.N[i], w = g.W[i]; hl.push([c[0] + nn[0] * w * .62, c[1] + nn[1] * w * .62]); }
  s += L(ptsD(hl), '#ffffff', .8, op(.35));
  return s;
}
/* 先の細い長い羽（中心線に沿う） */
function plume(pts, w0, fill, o) {
  o = o || {};
  const g = tubeGeo(pts, t => w0 * Math.sin(Math.PI * Math.min(1, t * 1.15 + .05)) * (1 - t * .55) + .4, 8);
  let s = P(tubePath(g), fill, o.ex || '');
  s += L(ptsD(g.c.slice(1, -2)), o.rib || INK, .5, op(.55));
  if (o.eye) { const e = g.c[Math.floor(g.m * .8)]; s += C(e[0], e[1], w0 * .42, o.eye, ' stroke-width=".7"') + Cn(e[0], e[1], w0 * .2, INK, op(.7)); }
  return s;
}
